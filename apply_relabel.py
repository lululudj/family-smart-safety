def imread_cn(p):
    return cv2.imdecode(np.fromfile(p, dtype=np.uint8), cv2.IMREAD_COLOR)

def imwrite_cn(p, img, q=86):
    cv2.imencode(".jpg", img, [cv2.IMWRITE_JPEG_QUALITY, q])[1].tofile(p)

def find(short):
    for split in ("train", "val"):
        p = os.path.join(DS, "images", split, "20261017_" + short + ".jpg")
        if os.path.isfile(p):
            return split, p
    return None, None

def to_yolo(x1, y1, x2, y2):
    cx = (x1 + x2) / 2 / W
    cy = (y1 + y2) / 2 / H
    bw = (x2 - x1) / W
    bh = (y2 - y1) / H
    return f"0 {cx:.6f} {cy:.6f} {bw:.6f} {bh:.6f}"

