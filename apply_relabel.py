def main():
    # 备份
    bak = os.path.join(OUT, "labels_backup")
    os.makedirs(bak, exist_ok=True)
    for split in ("train", "val"):
        src = os.path.join(DS, "labels", split)
        dst = os.path.join(bak, split)
        os.makedirs(dst, exist_ok=True)
        for f in os.listdir(src):
            if f.endswith(".txt"):
                shutil.copy2(os.path.join(src, f), os.path.join(dst, f))

    stats = {"delete": 0, "fix": 0, "new": 0, "missing": []}
    def lbl_path(split, short):
        return os.path.join(DS, "labels", split, "20261017_" + short + ".txt")

    for short in DELETE:
        split, _ = find(short)
        if split:
            open(lbl_path(split, short), "w").close()
            stats["delete"] += 1
    for short, box in FIX.items():
        split, _ = find(short)
        if split:
            with open(lbl_path(split, short), "w", encoding="utf-8") as f:
                f.write(to_yolo(*box) + "\n")
            stats["fix"] += 1
        else:
            stats["missing"].append(short)
    for short, box in NEW.items():
        split, _ = find(short)
        if split:
            with open(lbl_path(split, short), "w", encoding="utf-8") as f:
                f.write(to_yolo(*box) + "\n")
            stats["new"] += 1
        else:
            stats["missing"].append(short)

    # 统计
    n_pos = n_neg = 0
    for split in ("train", "val"):
        ld = os.path.join(DS, "labels", split)
        for f in os.listdir(ld):
            if f.endswith(".txt"):
                if os.path.getsize(os.path.join(ld, f)) > 0:
                    n_pos += 1
                else:
                    n_neg += 1
    stats["final_pos"] = n_pos
    stats["final_neg"] = n_neg
    with open(os.path.join(OUT, "relabel_stats.json"), "w", encoding="utf-8") as f:
        json.dump(stats, f, ensure_ascii=False, indent=1)
    print(json.dumps(stats, ensure_ascii=False, indent=1))

    # 渲染全部正标签核验图
    cells = []
    for split in ("train", "val"):
        idir = os.path.join(DS, "images", split)
        for fn in sorted(os.listdir(idir)):
            if not fn.endswith(".jpg"):
                continue
            lp = os.path.join(DS, "labels", split, fn[:-4] + ".txt")
            if not (os.path.isfile(lp) and os.path.getsize(lp) > 0):
                continue
            img = imread_cn(os.path.join(idir, fn))
            h, w = img.shape[:2]
            for line in open(lp, encoding="utf-8"):
                p = line.split()
                if len(p) == 5:
                    _, xc, yc, bw, bh = map(float, p)
                    x1, y1 = int((xc - bw / 2) * w), int((yc - bh / 2) * h)
                    x2, y2 = int((xc + bw / 2) * w), int((yc + bh / 2) * h)
                    cv2.rectangle(img, (x1, y1), (x2, y2), (0, 0, 255), 2)
            img = cv2.resize(img, (480, 270))
            cv2.putText(img, fn[-13:], (4, 22), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 255, 255), 2)
            cells.append(img)
    n = 0
    for k in range(0, len(cells), 9):
        b = cells[k:k + 9]
        while len(b) < 9:
            b.append(np.zeros((270, 480, 3), np.uint8))
        rows = [np.hstack(b[i:i + 3]) for i in range(0, 9, 3)]
        n += 1
        imwrite_cn(os.path.join(OUT, f"final_{n:02d}.jpg"), np.vstack(rows))
    print(f"核验图 final_01..{n:02d}.jpg，共 {len(cells)} 个正样本")

if __name__ == "__main__":
    main()
